export function courseTitleEn(title: string) {
  if (exactTitlesEn[title]) return exactTitlesEn[title];
  if (!han.test(title)) return title;
  let result = title;
  for (const [source, target] of sortedTerms) result = result.replaceAll(source, ` ${target} `);
  return result.replace(/\s+/g, " ").replace(/\s+([,.)])/g, "$1").replace(/([(])\s+/g, "$1").trim();
}

